import { copyFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, URL } from 'node:url';
const uRL = new URL('..', import.meta.url);
const repoRoot = fileURLToPath(uRL);
const runtimeDistDir = path.join(repoRoot, 'dist', 'runtime');
const mkdirSyncOptions = { recursive: true };
mkdirSync(runtimeDistDir, mkdirSyncOptions);
const joinedPath = path.join(repoRoot, 'src', 'runtime', 'humanize-init-page.cjs');
const joinedPath2 = path.join(runtimeDistDir, 'humanize-init-page.cjs');
copyFileSync(joinedPath, joinedPath2);
